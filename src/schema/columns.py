# This is the machine-checkable form of the project's central limitation.
#
# IoT-23's lightweight distribution ships Zeek `conn.log.labeled` only — no
# dns.log, no http.log, no ssl.log, and no payload. So the features that
# DEFINE this project's novelty are the ones it cannot supply:
#
#   resolution : 3 of 4 unavailable  (only a weak proxy for rpc_endpoint_ratio)
#   relay      : 1 of 4 unavailable  (upnp_addportmapping needs SSDP/SOAP)
#
# That is why the thesis cannot be tested on IoT-23, and why Track A measures
# false alarms on real benign traffic rather than the thesis. Encoding it here
# means docs/limitations.md can be generated from code instead of asserted in
# prose, and a test can fail if anyone ever quietly claims otherwise.

AVAIL_COMPUTABLE = "computable"    # derivable exactly from the source's fields
AVAIL_PROXY = "proxy"              # approximated; flagged on every row
AVAIL_UNAVAILABLE = "unavailable"  # not derivable; emitted as NaN

# The five features NO flow log can supply, identical to IoT-23's gap: they need
# a dns.log / http.log (resolution), SSDP/SOAP payload (upnp_addportmapping), or
# plaintext inspection (rc4_string_score) that a connection record never carries.
# Every flow-derived source forces exactly these to NaN — and because
# src/features/derive.py computes exactly the OTHER eleven, this set is what
# keeps a flow-derived source in agreement with the deriver (see the agreement
# check in derive_features). Changing it here without changing the deriver, or
# vice versa, fails loudly rather than emitting fabricated zeros.
_FLOW_UNAVAILABLE: tuple[str, ...] = (
    "ens_query_rate",
    "resolution_entropy",
    "serverlist_pull",
    "upnp_addportmapping",
    "rc4_string_score",
)


def _flow_availability(proxy: tuple[str, ...]) -> dict[str, str]:
    """Availability map for a flow-derived source.

    The five canonical gaps are ``unavailable``, the named features are
    ``proxy`` (approximations flagged on every row), and everything else is
    ``computable``. The computable-plus-proxy union is therefore always the
    eleven features derive_features produces, so any source built this way
    satisfies the derive/availability agreement check by construction. Only the
    proxy set differs between sources — it is the honesty label for how much a
    given telemetry format actually measures versus approximates.
    """
    unknown = set(proxy) - set(FEATURE_COLS)
    if unknown:
        raise ValueError(f"unknown proxy feature(s): {sorted(unknown)}")
    overlap = set(proxy) & set(_FLOW_UNAVAILABLE)
    if overlap:
        raise ValueError(
            f"feature(s) cannot be both proxy and unavailable: {sorted(overlap)}")
    out: dict[str, str] = {}
    for c in FEATURE_COLS:
        if c in _FLOW_UNAVAILABLE:
            out[c] = AVAIL_UNAVAILABLE
        elif c in proxy:
            out[c] = AVAIL_PROXY
        else:
            out[c] = AVAIL_COMPUTABLE
    return out


