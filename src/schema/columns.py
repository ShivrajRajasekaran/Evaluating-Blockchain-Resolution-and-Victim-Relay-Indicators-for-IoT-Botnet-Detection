# ---- quality_flags ---------------------------------------------------------
FLAG_MISSING_FEATURES = "missing_features"    # >=1 feature is NaN
FLAG_PROXY_FEATURES = "proxy_features"        # >=1 feature is an approximation
FLAG_LOW_FLOW_COUNT = "low_flow_count"        # window had too few flows
FLAG_SHORT_WINDOW = "short_window"            # window covers < min span
FLAG_UNMAPPED_LABEL = "unmapped_label"        # source label not in taxonomy
FLAG_SINGLE_PEER = "single_peer"              # only one remote peer seen
FLAG_LABEL_NOISE_INJECTED = "label_noise_injected"   # mock: label was flipped
# Real captures label individual FLOWS; this project's unit is a device-window,
# so a window can contain both benign and malicious flows. Aggregating to one
# class necessarily discards that. The flag carries the malicious flow fraction
# so a window that is 3% malicious is distinguishable from one that is 100%
# malicious — without it, a weak positive and an unambiguous one are the same
# row, and a reported false-negative rate cannot be interpreted.
FLAG_MIXED_LABEL_WINDOW = "mixed_label_window"

QUALITY_FLAG_NAMES: tuple[str, ...] = (
    FLAG_MISSING_FEATURES,
    FLAG_PROXY_FEATURES,
    FLAG_LOW_FLOW_COUNT,
    FLAG_SHORT_WINDOW,
    FLAG_UNMAPPED_LABEL,
    FLAG_SINGLE_PEER,
    FLAG_LABEL_NOISE_INJECTED,
    FLAG_MIXED_LABEL_WINDOW,
)

FLAG_SEP = ";"          # between flags
FLAG_ARG_SEP = ":"      # between a flag name and its argument
FLAG_LIST_SEP = "|"     # inside a flag argument, e.g. "missing_features:a|b"


def make_flags(flags: dict[str, list[str] | None] | None) -> str:
    """Render a flag dict to the canonical ``quality_flags`` string.

    ``{"missing_features": ["a", "b"], "low_flow_count": None}``
    becomes ``"missing_features:a|b;low_flow_count"``.

    Flags are emitted in QUALITY_FLAG_NAMES order so the string is stable and
    two runs producing the same flags produce byte-identical CSVs.
    """
    if not flags:
        return ""
    parts: list[str] = []
    for name in QUALITY_FLAG_NAMES:
        if name not in flags:
            continue
        arg = flags[name]
        if arg:
            parts.append(f"{name}{FLAG_ARG_SEP}{FLAG_LIST_SEP.join(sorted(arg))}")
        else:
            parts.append(name)
    return FLAG_SEP.join(parts)


def parse_flags(s: str | float | None) -> dict[str, list[str]]:
    """Inverse of :func:`make_flags`. Missing/NaN/empty all yield ``{}``."""
    if s is None or not isinstance(s, str) or not s.strip():
        return {}
    out: dict[str, list[str]] = {}
    for part in s.split(FLAG_SEP):
        part = part.strip()
        if not part:
            continue
        if FLAG_ARG_SEP in part:
            name, arg = part.split(FLAG_ARG_SEP, 1)
            out[name] = [a for a in arg.split(FLAG_LIST_SEP) if a]
        else:
            out[part] = []
    return out


