def features_for_groups(group_names) -> list[str]:
    """Feature columns belonging to the named groups, in canonical order."""
    wanted = set(group_names)
    unknown = wanted - set(FEATURE_GROUPS)
    if unknown:
        raise KeyError(f"unknown feature group(s): {sorted(unknown)}")
    return [c for g, cols in FEATURE_GROUPS.items() if g in wanted for c in cols]


def features_excluding(group_name: str) -> list[str]:
    """Feature columns with one group removed (drop-one diagnostic)."""
    if group_name not in FEATURE_GROUPS:
        raise KeyError(f"unknown feature group: {group_name}")
    return [c for g, cols in FEATURE_GROUPS.items()
            if g != group_name for c in cols]


def network_observable_features(cols=None) -> list[str]:
    """Drop the lab-only features from ``cols`` (default: all features)."""
    cols = list(FEATURE_COLS if cols is None else cols)
    return [c for c in cols if c not in LAB_ONLY_FEATURES]


def is_malicious_class(research_class: str) -> bool:
    return research_class in MALICIOUS_CLASSES


def binary_label_for(research_class: str) -> int:
    """Map a research_class to the 0/1 binary view.

    Raises on `unmapped` — an unmapped row has no defensible binary label and
    must be excluded from training rather than silently called benign.
    """
    if research_class in BENIGN_CLASSES:
        return 0
    if research_class in MALICIOUS_CLASSES:
        return 1
    raise ValueError(
        f"no binary label for research_class={research_class!r}; "
        f"`{CLS_UNMAPPED}` rows must be excluded, not defaulted"
    )
