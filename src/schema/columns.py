def features_by_availability(source: str, status: str) -> list[str]:
    """Feature columns with the given availability status for ``source``."""
    table = FEATURE_AVAILABILITY[source]
    return [c for c in FEATURE_COLS if table[c] == status]


def unavailable_features(source: str) -> list[str]:
    """Features that must be emitted as NaN for ``source``."""
    return features_by_availability(source, AVAIL_UNAVAILABLE)


def proxy_features(source: str) -> list[str]:
    """Features that are approximations for ``source`` (flag every row)."""
    return features_by_availability(source, AVAIL_PROXY)


def availability_summary(source: str) -> dict[str, dict[str, int]]:
    """Per-group counts of computable / proxy / unavailable for ``source``.

    Used by src/reports to generate the limitation table in the paper, so the
    numbers in the write-up are read from the schema rather than retyped.
    """
    table = FEATURE_AVAILABILITY[source]
    out: dict[str, dict[str, int]] = {}
    for group, cols in FEATURE_GROUPS.items():
        counts = {AVAIL_COMPUTABLE: 0, AVAIL_PROXY: 0, AVAIL_UNAVAILABLE: 0}
        for c in cols:
            counts[table[c]] += 1
        out[group] = counts
    return out


