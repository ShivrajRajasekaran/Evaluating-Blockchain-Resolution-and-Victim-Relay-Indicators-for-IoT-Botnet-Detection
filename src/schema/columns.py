"""
schema/columns.py — THE single source of truth for every column in this project.

Project: Evaluating Blockchain-Resolution and Victim-Relay Indicators for
         IoT Botnet Detection

Scope:   DEFENSIVE measurement only. No attack capability, no network activity,
         no contact with real infrastructure. See docs/ethics-and-containment.md.

WHY THIS FILE EXISTS
--------------------
The prototype (`prototype/`) emitted 16 features and one binary label, and
nothing else. That made three things impossible:

  * grouped splits      — no device identifier to group by
  * temporal splits      — no timestamp to order by
  * provenance auditing  — no record of where a row came from

Worse, it made a fourth thing *invisible*: if real-capture rows and locally
generated mock rows were ever concatenated, no column would reveal it, and a
model could learn "which capture is this?" instead of "is this malicious?" and
report a high F1 that measures nothing.

Every column below exists to make one of those four failures either possible
to do correctly, or impossible to do accidentally.

THE TWO-TRACK RULE (non-negotiable, enforced in schema/validate.py)
-------------------------------------------------------------------
Real and mock observations describe DISJOINT label spaces:

    Track A (real, IoT-23)   benign_real, traditional_c2,
                             traditional_botnet_activity
    Track B (mock, local)    benign_mock, blockchain_resolution_mock,
                             victim_relay_mock, combined_mock

No row may carry a research_class from the other track's list. No experiment
may train a single model over the union. The only permitted crossing is
one-directional and reported as a false-positive rate, never as accuracy:
score a Track-B-trained detector against Track-A benign rows.

The reason is not fastidiousness. Real IoT-23 captures physically cannot
contain blockchain-resolution or victim-relay behaviour — that behaviour is
newer than the captures. A model trained on the union would separate the
classes using capture artefacts (TTL, MTU, clock resolution, byte-count
granularity) and the resulting score would be indistinguishable from success.
"""
